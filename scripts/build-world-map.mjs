// Generates the Global Network section's dot-matrix map, once, ahead of
// time — so no map library or geometry ships to the browser.
//
//   node scripts/build-world-map.mjs
//
// Outputs:
//   public/images/network-map.svg   — the land as a grid of dots
//   src/content/networkMap.ts       — the same projection's coordinates for
//                                     each country marker, for the arcs
//
// Re-run only if the crop, projection or markers change.

import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoContains, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const WIDTH = 1000;
const DOT_SPACING = 10;
const DOT_RADIUS = 2.3;

// Europe -> Australia: everything the six origins and the destination
// need, without the Americas taking up half the frame.
const CROP = { west: -12, east: 160, south: -46, north: 58 };

// Approximate country positions — markers stand for the country, not a
// specific facility or city.
const ORIGINS = [
  { name: "Italy", lon: 12.5, lat: 42.8 },
  { name: "India", lon: 78.9, lat: 21.8 },
  { name: "Sri Lanka", lon: 80.7, lat: 7.8 },
  { name: "Bangladesh", lon: 90.3, lat: 23.8 },
  { name: "China", lon: 104.5, lat: 33.5 },
  { name: "Vietnam", lon: 106.4, lat: 15.2 },
];
const DESTINATION = { name: "Australia", lon: 134.5, lat: -25.5 };

const topo = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url))
);
const land = feature(topo, topo.objects.land);

// Fit to points sampled along the crop's edges. (A plain rectangle
// Polygon is ambiguous on a sphere — d3 reads its winding as "everything
// except this box" and fits the whole globe.)
const edge = [];
for (let t = 0; t <= 1; t += 0.05) {
  const lon = CROP.west + (CROP.east - CROP.west) * t;
  const lat = CROP.south + (CROP.north - CROP.south) * t;
  edge.push([lon, CROP.north], [lon, CROP.south], [CROP.west, lat], [CROP.east, lat]);
}
const cropOutline = { type: "MultiPoint", coordinates: edge };

const projection = geoNaturalEarth1().fitWidth(WIDTH, cropOutline);
const [[, y0], [, y1]] = geoPath(projection).bounds(cropOutline);
const HEIGHT = Math.round(y1 - y0);
projection.translate([projection.translate()[0], projection.translate()[1] - y0]);

const dots = [];
for (let y = DOT_SPACING / 2; y < HEIGHT; y += DOT_SPACING) {
  for (let x = DOT_SPACING / 2; x < WIDTH; x += DOT_SPACING) {
    const lonLat = projection.invert([x, y]);
    if (lonLat && geoContains(land, lonLat)) {
      dots.push(`<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${DOT_RADIUS}"/>`);
    }
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}"><g fill="#100d09" fill-opacity="0.16">${dots.join("")}</g></svg>\n`;
writeFileSync(new URL("../public/images/network-map.svg", import.meta.url), svg);

const project = ({ name, lon, lat }) => {
  const [x, y] = projection([lon, lat]);
  return { name, lon, lat, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
};

const ts = `// GENERATED by scripts/build-world-map.mjs — do not edit by hand.
// Marker positions in the same projection and viewBox as
// public/images/network-map.svg, with the longitude and latitude they
// came from (the homepage globe places them from those).

export const NETWORK_MAP = {
  width: ${WIDTH},
  height: ${HEIGHT},
  origins: ${JSON.stringify(ORIGINS.map(project), null, 2).replace(/\n/g, "\n  ")},
  destination: ${JSON.stringify(project(DESTINATION))},
} as const;
`;
writeFileSync(new URL("../src/content/networkMap.ts", import.meta.url), ts);

console.log(`map ${WIDTH}x${HEIGHT}, ${dots.length} dots, ${Math.round(svg.length / 1024)}KB`);
